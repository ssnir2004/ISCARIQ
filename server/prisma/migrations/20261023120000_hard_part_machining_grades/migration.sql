-- Ceramic types used here (kept if they exist under any spelling).
INSERT INTO "GradeType" ("id", "name", "family")
SELECT 'ceramic-' || replace(lower(t."type"), ' ', '-'), t."type", 'CERAMIC'
FROM (SELECT DISTINCT "type" FROM "_hp_grade" WHERE "type" IS NOT NULL) t
WHERE NOT EXISTS (SELECT 1 FROM "GradeType" x WHERE x."family" = 'CERAMIC' AND lower(x."name") = lower(t."type"))
ON CONFLICT DO NOTHING;

-- Missing grades.
INSERT INTO "Grade" ("id", "name", "family")
SELECT 'hpm-grade-' || lower(h."name"), h."name", h."family"
FROM "_hp_grade" h
WHERE NOT EXISTS (SELECT 1 FROM "Grade" g WHERE upper(replace(g."name", ' ', '')) = h."name")
ON CONFLICT DO NOTHING;

CREATE TEMP TABLE "_hp_match" AS
SELECT g."id", h.* FROM "_hp_grade" h
JOIN "Grade" g ON upper(replace(g."name", ' ', '')) = h."name" AND g."family" = h."family";

UPDATE "Grade" g SET "description" = m."description"
FROM "_hp_match" m
WHERE g."id" = m."id" AND (
  g."description" IS NULL OR trim(g."description") = ''
  OR lower(trim(g."description")) IN ('alumina', 'sialon', 'siaion', 'whisker', 'whiskers', 'bidemics', 'silicon nitride')
  OR lower(trim(g."description")) = (SELECT lower(t."name") FROM "GradeType" t WHERE t."id" = g."typeId")
);

UPDATE "Grade" g SET "typeId" = (SELECT t."id" FROM "GradeType" t WHERE t."family" = 'CERAMIC' AND lower(t."name") = lower(m."type") LIMIT 1)
FROM "_hp_match" m
WHERE g."id" = m."id" AND g."typeId" IS NULL AND m."type" IS NOT NULL;

UPDATE "Grade" g SET "iso513Groups" = m."iso"
FROM "_hp_match" m
WHERE g."id" = m."id" AND (g."iso513Groups" IS NULL OR cardinality(g."iso513Groups") = 0);

INSERT INTO "_ApplicationToGrade" ("A", "B")
SELECT a."id", m."id"
FROM "_hp_match" m
JOIN "Application" a ON lower(a."name") = ANY(SELECT lower(x) FROM unnest(m."apps") x)
WHERE NOT EXISTS (SELECT 1 FROM "_ApplicationToGrade" ag WHERE ag."B" = m."id")
ON CONFLICT DO NOTHING;

-- Coated CBN grades (…C) join the "Coated" group when they have no group.
INSERT INTO "_GradeToGradeSet" ("A", "B")
SELECT m."id", s."id"
FROM "_hp_match" m
JOIN "GradeSet" s ON s."family" = 'CBN' AND lower(s."name") = 'coated'
WHERE m."family" = 'CBN' AND m."name" LIKE '%C' AND NOT EXISTS (SELECT 1 FROM "_GradeToGradeSet" gs WHERE gs."A" = m."id")
ON CONFLICT DO NOTHING;

