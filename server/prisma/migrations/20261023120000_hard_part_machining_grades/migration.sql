-- Each recommendation's material: the first in its ISO group whose name
-- matches (e.g. "Gray cast iron"), else the group itself.
CREATE TEMP TABLE "_hp_rec_mat" AS
SELECT r.*, m."id" AS "gradeId", COALESCE(
  (SELECT x."id" FROM "Material" x WHERE x."iso513Group" = r."iso" AND NOT x."isCategory" AND x."name" ~* r."rx" ORDER BY x."name" LIMIT 1),
  (SELECT x."id" FROM "Material" x WHERE x."iso513Group" = r."iso" AND x."isCategory" ORDER BY x."name" LIMIT 1)
) AS "materialId"
FROM "_hp_rec" r
JOIN "_hp_match" m ON m."name" = r."grade" AND m."family" = r."family";

-- Only where the grade has no recommendation for that material yet (and
-- once per operation set).
DELETE FROM "_hp_rec_mat" r
WHERE r."materialId" IS NULL
   OR EXISTS (
     SELECT 1 FROM "GradeRecommendation" x JOIN "_GradeToGradeRecommendation" gx ON gx."B" = x."id"
     WHERE x."materialId" = r."materialId" AND gx."A" = r."gradeId" AND x."id" NOT IN (SELECT "id" FROM "_hp_rec"));

INSERT INTO "GradeRecommendation" ("id", "family", "materialId", "rough", "semiFinish", "finish", "vcMin", "vcRec", "vcMax", "feedMin", "feedMax", "apMin", "apMax", "dry", "wet", "notes", "position")
SELECT r."id", r."family", r."materialId", r."rough", r."semi", r."finish", r."vcMin", r."vcRec", r."vcMax", r."feedMin", r."feedMax", r."apMin", r."apMax", r."dry", r."wet", r."notes", 1000
FROM "_hp_rec_mat" r
ON CONFLICT DO NOTHING;

INSERT INTO "_GradeToGradeRecommendation" ("A", "B")
SELECT r."gradeId", r."id" FROM "_hp_rec_mat" r
ON CONFLICT DO NOTHING;

INSERT INTO "_ApplicationToGradeRecommendation" ("A", "B")
SELECT a."id", r."id" FROM "_hp_rec_mat" r JOIN "Application" a ON lower(a."name") = 'turning'
ON CONFLICT DO NOTHING;

DROP TABLE "_hp_rec_mat", "_hp_rec", "_hp_cmp", "_hp_match", "_hp_grade";
