-- only what is empty on existing ones (matched by name, ignoring spaces and
-- case): description (also when it is only the type's name, e.g. "SiAlON"),
-- ceramic type, ISO groups, applications, the CBN "Coated" group; adds the
-- competitors' equivalent grades (catalog pp. 323-324) that aren't listed and
-- recommended cutting conditions for materials (by name in the ISO group, else
-- the group itself) that have none for the grade.

